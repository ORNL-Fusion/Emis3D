# mock.py
"""
The MOCK machine: a small synthetic tokamak that ships with Emis3D for tests,
examples and `emis3d selftest`. It is not a real device; do not use its
numbers for physics.

Everything is analytic and generated by this module:

* wall      D-shaped polygon, R0 = 1.7 m, a = 0.6 m, elongation 1.7, triangularity 0.35
* cameras   8-channel pinhole cameras
            POL_A, POL_C   poloidal fans above the midplane at 45 and 285 deg
            POL_B          poloidal fan below the midplane at 165 deg
            SKEW           same position as POL_A's twin at 165 deg, skewed 30 deg
                           toroidally, so its chords have toroidal and poloidal parts
            WRAP           skewed camera at 20 deg whose chords cross phi = 0
* etendues  analytic, from the built camera geometry (deterministic)

Regenerate the shipped files after changing anything here:

    python -m emis3d.mock                  # writes src/emis3d/machines/MOCK
    python -m emis3d.mock --out DIR        # writes DIR/MOCK

Tests can build variants (for example a machine with only two toroidal
locations) in a temporary workspace with `mock_workspace`.
"""

from __future__ import annotations

import argparse
import shutil
import tempfile
from dataclasses import dataclass, field, replace
from pathlib import Path

import numpy as np
import yaml

NAME = "MOCK"
HEADER = "# Generated by emis3d.mock; do not edit. Regenerate with `python -m emis3d.mock`.\n"


@dataclass(frozen=True)
class CameraSpec:
    name: str
    phi_deg: float              # toroidal position, Emis3D convention
    z: float = 0.8              # camera height [m]; negative for a camera below the midplane
    R: float = 2.30             # camera major radius [m]
    rotation_deg: float = 125.0 # view direction for a camera above the midplane (Diagnostic's
                                # CAMERA_ROTATION); mirrored automatically for z < 0
    skew_deg: float = 0.0       # toroidal tilt of the viewing direction
    n_channels: int = 8


@dataclass(frozen=True)
class MockSpec:
    R0: float = 1.70
    a: float = 0.60
    kappa: float = 1.70
    delta: float = 0.35
    n_wall: int = 96
    cameras: tuple = field(default_factory=lambda: (
        CameraSpec("POL_A", 45.0),
        CameraSpec("POL_B", 165.0, z=-0.8),
        CameraSpec("POL_C", 285.0),
        CameraSpec("SKEW", 165.0, skew_deg=30.0),
        CameraSpec("WRAP", 20.0, skew_deg=30.0),
    ))
    # pinhole camera geometry shared by every camera [m]
    slit: float = 2.0e-4
    foil_width: float = 2.0e-3
    foil_height: float = 5.0e-3
    slit_sensor_separation: float = 0.03
    foil_separation: float = 4.0e-3


DEFAULT = MockSpec()


# ----------------------------------------------------------------------------
# Geometry
# ----------------------------------------------------------------------------


def wall_polygon(spec: MockSpec = DEFAULT) -> np.ndarray:
    """Closed D-shaped wall, (n_wall + 1, 2) array of (R, z) [m]."""
    th = np.linspace(0.0, 2.0 * np.pi, spec.n_wall, endpoint=False)
    R = spec.R0 + spec.a * np.cos(th + spec.delta * np.sin(th))
    z = spec.kappa * spec.a * np.sin(th)
    rz = np.column_stack([R, z])
    return np.vstack([rz, rz[:1]])


def wall_area_and_volume(rz: np.ndarray) -> tuple[float, float]:
    """Polygon area and torus volume by Pappus' theorem."""
    R, z = rz[:-1, 0], rz[:-1, 1]
    R2, z2 = np.roll(R, -1), np.roll(z, -1)
    cross = R * z2 - R2 * z
    area = 0.5 * cross.sum()
    R_centroid = ((R + R2) * cross).sum() / (6.0 * area)
    return abs(area), abs(2.0 * np.pi * R_centroid * area)


def camera_config(cam: CameraSpec, spec: MockSpec = DEFAULT) -> dict:
    n = cam.n_channels
    positions = [float(p) for p in (np.arange(n)[::-1] - (n - 1) / 2.0)]   # foil shifts in units of separation
    cfg = {
        "NAME": cam.name,
        "GROUP_NAME": cam.name,
        "NUM_CHANNELS": n,
        "TYPE": "planar",
        "CHANNEL_TAGS": [f"{cam.name}{i + 1:02d}" for i in range(n)],
        "BUILD_TYPE": "FROM PRIMITIVES",
        "SLIT_WIDTH": spec.slit,
        "SLIT_HEIGHT": spec.slit,
        "FOIL_WIDTH": spec.foil_width,
        "FOIL_HEIGHT": spec.foil_height,
        "FOIL_CORNER_CURVATURE": 0.0005,
        "SLIT_SENSOR_SEPARATION": spec.slit_sensor_separation,
        "FOIL_SEPARATION": spec.foil_separation,
        "FOIL_POSITIONS": positions,
        "CAMERA_POSITION_R_Z_PHI": [cam.R, cam.z, cam.phi_deg],
        # Diagnostic measures an upward-facing camera's rotation from +z, so the
        # mirror image of a top camera at rotation r is r - 180
        "CAMERA_ROTATION": cam.rotation_deg if cam.z > 0 else cam.rotation_deg - 180.0,
        "CAMERA_DOWNWARD_FACING": bool(cam.z > 0),
    }
    if cam.skew_deg:
        cfg["SKEW_ANGLE"] = cam.skew_deg
    return cfg


def settings(spec: MockSpec = DEFAULT) -> dict:
    _, volume = wall_area_and_volume(wall_polygon(spec))
    return {
        "MACHINE": {
            "device": NAME,
            "volume": float(round(volume, 4)),
            "majorRadius": spec.R0,
            "minorRadius": spec.a,
            "wallFileName": "MOCK_wall.txt",
            "numInjectors": 1,
        },
        "BOLOMETERS": {c.name: {"configFileName": f"{c.name}_config.yaml"} for c in spec.cameras},
    }


# ----------------------------------------------------------------------------
# Writing the machine folder
# ----------------------------------------------------------------------------


def _dump(path: Path, data: dict) -> None:
    path.write_text(HEADER + yaml.safe_dump(data, sort_keys=False, default_flow_style=None))


def _analytic_etendues(machines_root: Path, cam_names: list[str]) -> dict[str, list[float]]:
    """Analytic etendue of every foil, from cameras built exactly as Emis3D builds them."""
    from raysect.optical import World

    from emis3d.diagnostic import Bolometer
    from emis3d.workspace import Workspace

    ws = Workspace.resolve(workspace=machines_root, overrides={"machines": [str(machines_root)]},
                           env={}, user_config=machines_root / "_none.yaml")
    out = {}
    for name in cam_names:
        b = Bolometer(world=World(), tokamakName=NAME, configFileName=f"{name}_config.yaml", workspace=ws)
        vals = []
        for foil in b.bolometer_camera:
            Adet = foil.x_width * foil.y_width
            Aslit = foil.slit.dx * foil.slit.dy
            s = foil.sightline_vector.normalise()
            d = foil.centre_point.vector_to(foil.slit.centre_point).length
            vals.append(float(f"{Adet * Aslit * s.dot(foil.normal_vector) * s.dot(foil.slit.normal_vector) / d**2:.6e}"))
        out[name] = vals
    return out


def build(machines_root: str | Path, spec: MockSpec = DEFAULT) -> Path:
    """Write <machines_root>/MOCK and return its path."""
    root = Path(machines_root)
    mdir = root / NAME
    if mdir.exists():
        shutil.rmtree(mdir)
    (mdir / "inputs" / "sxrInfo").mkdir(parents=True)

    _dump(mdir / f"{NAME}_settings.yaml", settings(spec))
    rz = wall_polygon(spec)
    with open(mdir / "inputs" / "MOCK_wall.txt", "w") as fh:
        fh.write("".join(f"{R:.6f} {z:.6f}\n" for R, z in rz))

    cfgs = {c.name: camera_config(c, spec) for c in spec.cameras}
    for name, cfg in cfgs.items():
        _dump(mdir / "inputs" / "sxrInfo" / f"{name}_config.yaml", cfg)
    etendues = _analytic_etendues(root, list(cfgs))
    for name, cfg in cfgs.items():
        cfg["ETENDUE"] = etendues[name]
        _dump(mdir / "inputs" / "sxrInfo" / f"{name}_config.yaml", cfg)
    return mdir


def mock_workspace(path: str | Path, cameras: list[CameraSpec] | None = None, **spec_changes):
    """
    A workspace at `path` whose MOCK machine is a variant of the shipped one,
    e.g. mock_workspace(tmp_path, cameras=[CameraSpec("A", 90), CameraSpec("B", 225)]).
    """
    from emis3d.workspace import Workspace

    path = Path(path)
    spec = replace(DEFAULT, **spec_changes)
    if cameras is not None:
        spec = replace(spec, cameras=tuple(cameras))
    build(path / "machines", spec)
    return Workspace.resolve(workspace=path, env={}, user_config=path / "_none.yaml")


# ----------------------------------------------------------------------------
# Self-test: the whole pipeline on MOCK with a known answer
# ----------------------------------------------------------------------------


def selftest(workdir: str | Path | None = None, pixel_samples: int = 50, verbose: bool = True) -> dict:
    """
    Build three ElongatedRing radDists on MOCK, fabricate measurements from one
    of them with a known toroidal shape, run the full Emis3D fit and check that
    the right radDist is chosen. Returns a summary; raises AssertionError on failure.
    """
    import h5py

    import emis3d.util_emis3D as Util_emis3D
    from emis3d.emis3D import Emis3D
    from emis3d.radDist import ElongatedRing
    from emis3d.workspace import Workspace, set_workspace

    tmp = None
    if workdir is None:
        tmp = tempfile.TemporaryDirectory(prefix="emis3d_selftest_")
        workdir = tmp.name
    ws_dir = Path(workdir)
    for d in ("raddists/MOCK/ring", "measurements/MOCK/1", "runs/selftest"):
        (ws_dir / d).mkdir(parents=True, exist_ok=True)
    if not (ws_dir / "emis3d.yaml").exists():   # a real workspace: run configs inside it find it
        (ws_dir / "emis3d.yaml").write_text("# Workspace created by emis3d.mock.selftest\nversion: 1\n")
    ws = Workspace.resolve(workspace=ws_dir, env={}, user_config=ws_dir / "_none.yaml")
    set_workspace(ws)

    def say(msg):
        if verbose:
            print(msg, flush=True)

    # b_true is kept small enough that the fitted amplitude stays inside its
    # bounds of [1, 6] (review issue 4); the check below fails loudly if it does not
    inj, b_true, true_idx = 225.0, 0.3, 1
    starts = [(1.55, 0.0), (1.75, 0.15), (1.95, -0.15)]
    rds = []
    for i, (R, z) in enumerate(starts):
        say(f"radDist {i + 1}/{len(starts)}: ElongatedRing at R={R}, z={z}")
        rd = ElongatedRing(startR=R, startZ=z, config={
            "distType": "ElongatedRing", "tokamakName": NAME, "units": "Brightness",
            "injectionLocation": inj, "eqFileName": None, "sigma_R": 0.2, "sigma_z": 0.25,
            "rotationAngle": 0.0, "saveRunsDirectoryName": "ring",
            "BOLOMETER_PROPS": {"pixelSamples": pixel_samples, "numProcessors": 1, "seed": 7},
        })
        rd.build()
        rds.append(rd)

    # measurements from radDist `true_idx`, scaled toroidally exp(-b dphi^2) about the injector
    say("fabricating measurements")
    truth = rds[true_idx]
    mu = np.deg2rad(inj)
    rng = np.random.default_rng(0)
    T = np.linspace(9.0, 11.0, 101)
    bolos = {}
    for bolo in truth.tokamak.bolometers:
        tags = bolo.info["CHANNEL_TAGS"]
        vals = np.array([float(np.sum(v)) for v in truth.data["Brightness"]["elongatedRing"][bolo.name]])
        phis = truth.data["observed_phi_loc"]["elongatedRing"][bolo.name]
        dphi = np.array([Util_emis3D.find_dphi(np.atleast_1d(p), mu, "elongatedRing")[0] for p in phis])
        clean = 1.0e3 * vals * np.exp(-b_true * dphi**2)
        sig = clean[:, None] * (1.0 + 0.03 * rng.normal(size=(len(tags), T.size)))
        with h5py.File(ws_dir / "measurements/MOCK/1" / f"{bolo.name}.h5", "w") as f:
            f.create_dataset("channelOrder", data=tags)
            f.create_dataset("TIME", data=T)
            f.create_dataset("DATA_CALIBRATED", data=sig)
        bolos[bolo.name] = {"dataFileName": f"1/{bolo.name}.h5", "scalingFactor": 1.0}

    run = ws_dir / "runs/selftest/run.yaml"
    run.write_text(yaml.safe_dump({
        "tokamakName": NAME, "shot": 1, "dt": 0.2, "injectionLocation": inj,
        "radDistDirectories_LocIndependent": ["ring"], "radDistDirectories_LocDependent": [],
        "BOLOMETERS": bolos, "scale_def": "exponential", "error_definition": "exponential",
        "enable_dphi_scaling": True, "vary_peak_rad_location": False,
    }, sort_keys=False))

    say("fitting")
    np.random.seed(0)
    e = Emis3D(runConfigName=str(run), workspace=ws)
    e._perform_fits(evalTime=10.0)
    e._save_bestFits()
    best = e.bestFits[10.0]
    tag = Util_emis3D.loc_tag(inj)
    a_par = best["fit"].params[f"a_{tag}"]
    chosen = (round(best["radDistInfo"]["startR"], 3), round(best["radDistInfo"]["startZ"], 3))
    summary = {
        "chosen_radDist": chosen,
        "true_radDist": starts[true_idx],
        "b_fit": float(best["fit"].params[f"b_elongatedRing_{tag}"].value),
        "b_true": b_true,
        "a_fit": float(a_par.value),
        "results": str(e._results_dir()),
    }
    assert chosen == starts[true_idx], f"self-test chose {chosen}, expected {starts[true_idx]}"
    assert a_par.min + 1e-3 < a_par.value < a_par.max - 1e-3, (
        f"amplitude a = {a_par.value:.3f} reached a bound [{a_par.min}, {a_par.max}]")
    assert abs(summary["b_fit"] - b_true) < 0.1 * b_true, f"b = {summary['b_fit']:.3f}, expected {b_true}"
    say(f"self-test passed: chose R, z = {chosen}, b = {summary['b_fit']:.3f} (true {b_true})")
    set_workspace(None)
    if tmp is not None:
        tmp.cleanup()
    return summary


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description="Write the MOCK machine definition")
    p.add_argument("--out", default=str(Path(__file__).resolve().parent / "machines"),
                   help="machines folder to write MOCK into (default: the package's built-in machines)")
    args = p.parse_args(argv)
    print(f"MOCK written to {build(args.out)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
