def selftest(workdir: str | Path | None = None, pixel_samples: int = 50, verbose: bool = True) -> dict:
    """
    Build three ElongatedRing radDists on MOCK, fabricate measurements from one
    of them with a known toroidal shape, run the full Emis3D fit and check that
    the right radDist is chosen. Returns a summary; raises AssertionError on failure.
    """
    import h5py

    import emis3d.util_emis3D as Util_emis3D
    from emis3d.emis3D import Emis3D
    from emis3d.radDist import ElongatedRing
    from emis3d.workspace import Workspace, set_workspace

    tmp = None
    if workdir is None:
        tmp = tempfile.TemporaryDirectory(prefix="emis3d_selftest_")
        workdir = tmp.name
    ws_dir = Path(workdir)
    for d in ("raddists/MOCK/ring", "measurements/MOCK/1", "runs/selftest"):
        (ws_dir / d).mkdir(parents=True, exist_ok=True)
    if not (ws_dir / "emis3d.yaml").exists():   # a real workspace: run configs inside it find it
        (ws_dir / "emis3d.yaml").write_text("# Workspace created by emis3d.mock.selftest\nversion: 1\n")
    ws = Workspace.resolve(workspace=ws_dir, env={}, user_config=ws_dir / "_none.yaml")
    set_workspace(ws)

    def say(msg):
        if verbose:
            print(msg, flush=True)

    # b_true is kept small enough that the fitted amplitude stays inside its
    # bounds of [1, 6] (review issue 4); the check below fails loudly if it does not
    inj, b_true, true_idx = 225.0, 0.3, 1
    starts = [(1.55, 0.0), (1.75, 0.15), (1.95, -0.15)]
    rds = []
    for i, (R, z) in enumerate(starts):
        say(f"radDist {i + 1}/{len(starts)}: ElongatedRing at R={R}, z={z}")
        rd = ElongatedRing(startR=R, startZ=z, config={
            "distType": "ElongatedRing", "tokamakName": NAME, "units": "Brightness",
            "injectionLocation": inj, "eqFileName": None, "sigma_R": 0.2, "sigma_z": 0.25,
            "rotationAngle": 0.0, "saveRunsDirectoryName": "ring",
            "BOLOMETER_PROPS": {"pixelSamples": pixel_samples, "numProcessors": 1, "seed": 7},
        })
        rd.build()
        rds.append(rd)

    # measurements from radDist `true_idx`, scaled toroidally exp(-b dphi^2) about the injector
    say("fabricating measurements")
    truth = rds[true_idx]
    mu = np.deg2rad(inj)
    rng = np.random.default_rng(0)
    T = np.linspace(9.0, 11.0, 101)
    bolos = {}
    for bolo in truth.tokamak.bolometers:
        tags = bolo.info["CHANNEL_TAGS"]
        vals = np.array([float(np.sum(v)) for v in truth.data["Brightness"]["elongatedRing"][bolo.name]])
        phis = truth.data["observed_phi_loc"]["elongatedRing"][bolo.name]
        dphi = np.array([Util_emis3D.find_dphi(np.atleast_1d(p), mu, "elongatedRing")[0] for p in phis])
        clean = 1.0e3 * vals * np.exp(-b_true * dphi**2)
        sig = clean[:, None] * (1.0 + 0.03 * rng.normal(size=(len(tags), T.size)))
        with h5py.File(ws_dir / "measurements/MOCK/1" / f"{bolo.name}.h5", "w") as f:
            f.create_dataset("channelOrder", data=tags)
            f.create_dataset("TIME", data=T)
            f.create_dataset("DATA_CALIBRATED", data=sig)
        bolos[bolo.name] = {"dataFileName": f"1/{bolo.name}.h5", "scalingFactor": 1.0}

    run = ws_dir / "runs/selftest/run.yaml"
    run.write_text(yaml.safe_dump({
        "tokamakName": NAME, "shot": 1, "tstart": 10.0, "dt": 0.2, "injectionLocation": inj,
        "radDistDirectories_LocIndependent": ["ring"], "radDistDirectories_LocDependent": [],
        "BOLOMETERS": bolos, "scale_def": "exponential",
        "enable_dphi_scaling": True, "vary_peak_rad_location": False,
    }, sort_keys=False))

    say("fitting")
    np.random.seed(0)
    e = Emis3D(runConfigName=str(run), workspace=ws)
    assert e._perform_fits() == [10.0]  # times from the run config
    e._save_bestFits()
    best = e.bestFits[10.0]
    tag = Util_emis3D.loc_tag(inj)
    a_par = best["fit"].params[f"a_{tag}"]
    chosen = (round(best["radDistInfo"]["startR"], 3), round(best["radDistInfo"]["startZ"], 3))
    summary = {
        "chosen_radDist": chosen,
        "true_radDist": starts[true_idx],
        "b_fit": float(best["fit"].params[f"b_elongatedRing_{tag}"].value),
        "b_true": b_true,
        "a_fit": float(a_par.value),
        "results": str(e._results_dir()),
    }
    assert chosen == starts[true_idx], f"self-test chose {chosen}, expected {starts[true_idx]}"
    assert a_par.min + 1e-3 < a_par.value < a_par.max - 1e-3, (
        f"amplitude a = {a_par.value:.3f} reached a bound [{a_par.min}, {a_par.max}]")
    assert abs(summary["b_fit"] - b_true) < 0.1 * b_true, f"b = {summary['b_fit']:.3f}, expected {b_true}"
    say(f"self-test passed: chose R, z = {chosen}, b = {summary['b_fit']:.3f} (true {b_true})")
    set_workspace(None)
    if tmp is not None:
        tmp.cleanup()
    return summary


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description="Write the MOCK machine definition")
    p.add_argument("--out", default=str(Path(__file__).resolve().parent / "machines"),
                   help="machines folder to write MOCK into (default: the package's built-in machines)")
    args = p.parse_args(argv)
    print(f"MOCK written to {build(args.out)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
