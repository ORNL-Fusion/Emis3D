def solovev(eq: EquilibriumSpec = DEFAULT_EQ) -> dict:
    """Axis, flux function and its constants for the Solov'ev equilibrium."""
    R0 = float(np.sqrt((eq.R_in**2 + eq.R_out**2) / 2.0))
    c = eq.B0 / (2.0 * R0**2 * eq.kappa * eq.q0)

    def psi(R, Z):
        return c * (R**2 * Z**2 + eq.kappa**2 / 4.0 * (R**2 - R0**2) ** 2)

    def grad_psi(R, Z):
        dR = c * (2.0 * R * Z**2 + eq.kappa**2 * R * (R**2 - R0**2))
        dZ = c * 2.0 * R**2 * Z
        return dR, dZ

    return {"R0": R0, "c": c, "psi": psi, "grad": grad_psi, "psi_b": float(psi(eq.R_out, 0.0)), "F": R0 * eq.B0}


def flux_surface(sol: dict, psi_value: float, n: int = 720) -> tuple[np.ndarray, np.ndarray]:
    """Points (R, Z) of the flux surface psi = psi_value, by bisection along rays from the axis."""
    th = np.linspace(0.0, 2.0 * np.pi, n, endpoint=False)
    lo, hi = np.zeros(n), np.full(n, 2.0)
    for _ in range(80):
        mid = 0.5 * (lo + hi)
        inside = sol["psi"](sol["R0"] + mid * np.cos(th), mid * np.sin(th)) < psi_value
        lo, hi = np.where(inside, mid, lo), np.where(inside, hi, mid)
    return sol["R0"] + lo * np.cos(th), lo * np.sin(th)


def _surface_integrals(sol: dict, psi_value: float) -> tuple[float, float]:
    """(q, integral of B_pol dl) on one flux surface; q = F/(2 pi) * loop integral of dl / (R |grad psi|)."""
    R, Z = flux_surface(sol, psi_value)
    dR, dZ = sol["grad"](R, Z)
    g = np.hypot(dR, dZ)
    dl = np.hypot(np.roll(R, -1) - np.roll(R, 1), np.roll(Z, -1) - np.roll(Z, 1)) / 2.0
    q = sol["F"] / (2.0 * np.pi) * np.sum(dl / (R * g))
    return float(q), float(np.sum(g / R * dl))


def equilibrium_gfile(spec: MockSpec = DEFAULT, eq: EquilibriumSpec = DEFAULT_EQ) -> dict:
    """The g-file contents for the Solov'ev equilibrium inside the MOCK wall."""
    sol = solovev(eq)
    Rg = np.linspace(eq.R_grid[0], eq.R_grid[1], eq.nR)
    Zg = np.linspace(eq.Z_grid[0], eq.Z_grid[1], eq.nZ)
    RR, ZZ = np.meshgrid(Rg, Zg, indexing="ij")
    psin = np.linspace(0.0, 1.0, eq.nR)
    psi_b = sol["psi_b"]

    # Grad-Shafranov: Delta* psi = 2 c (1 + kappa^2) R^2 = -mu0 R^2 p'  (F F' = 0)
    pprime = -2.0 * sol["c"] * (1.0 + eq.kappa**2) / MU0
    q = np.array([eq.q0] + [_surface_integrals(sol, x * psi_b)[0] for x in psin[1:]])
    Rb, Zb = flux_surface(sol, psi_b, n=128)
    wall = wall_polygon(spec)
    current = _surface_integrals(sol, psi_b)[1] / MU0

    rnd = lambda a: np.round(np.asarray(a, dtype=float), 9)  # noqa: E731  (identical text on every platform)
    return {
        "nx": eq.nR, "ny": eq.nZ,
        "rdim": float(Rg[-1] - Rg[0]), "zdim": float(Zg[-1] - Zg[0]),
        "rcentr": spec.R0, "rleft": float(Rg[0]), "zmid": 0.0,
        "rmagx": round(sol["R0"], 9), "zmagx": 0.0,
        "simagx": 0.0, "sibdry": round(psi_b, 12),
        "bcentr": round(sol["F"] / spec.R0, 9), "cpasma": round(current, 3),
        "fpol": rnd(np.full(eq.nR, sol["F"])),
        "pres": rnd(pprime * (psin - 1.0) * psi_b),
        "ffprime": np.zeros(eq.nR),
        "pprime": rnd(np.full(eq.nR, pprime)),
        "psi": rnd(sol["psi"](RR, ZZ)),
        "qpsi": rnd(q),
        "nbdry": int(Rb.size + 1), "rbdry": rnd(np.append(Rb, Rb[0])), "zbdry": rnd(np.append(Zb, Zb[0])),
        "nlim": int(len(wall)), "rlim": rnd(wall[:, 0]), "zlim": rnd(wall[:, 1]),
    }


def write_equilibrium(path: Path, spec: MockSpec = DEFAULT, eq: EquilibriumSpec = DEFAULT_EQ) -> Path:
    """Write the g-file. freeqdsk puts today's date in the header; it is fixed here so the file is reproducible."""
    import datetime
    import io

    from freeqdsk import geqdsk

    buf = io.StringIO()
    data: Any = equilibrium_gfile(spec, eq)  # freeqdsk accepts a plain dict of its fields
    geqdsk.write(data, buf, label="MOCK")
    text = buf.getvalue().replace(datetime.date.today().strftime("%d/%m/%Y"), "01/01/2026", 1)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    return path


def _dump(path: Path, data: dict) -> None:
    path.write_text(HEADER + yaml.safe_dump(data, sort_keys=False, default_flow_style=None))


def _analytic_etendues(machines_root: Path, cam_names: list[str]) -> dict[str, list[float]]:
    """Analytic etendue of every foil, from cameras built exactly as Emis3D builds them."""
    from raysect.optical import World

    from emis3d.diagnostic import Bolometer
    from emis3d.workspace import Workspace

    ws = Workspace.resolve(workspace=machines_root, overrides={"machines": [str(machines_root)]},
                           env={}, user_config=machines_root / "_none.yaml")
    out = {}
    for name in cam_names:
        b = Bolometer(world=World(), tokamakName=NAME, configFileName=f"{name}_config.yaml", workspace=ws)
        vals = []
        for foil in b.bolometer_camera:
            Adet = foil.x_width * foil.y_width
            Aslit = foil.slit.dx * foil.slit.dy
            s = foil.sightline_vector.normalise()
            d = foil.centre_point.vector_to(foil.slit.centre_point).length
            vals.append(float(f"{Adet * Aslit * s.dot(foil.normal_vector) * s.dot(foil.slit.normal_vector) / d**2:.6e}"))
        out[name] = vals
    return out


def build(machines_root: str | Path, spec: MockSpec = DEFAULT) -> Path:
    """Write <machines_root>/MOCK and return its path."""
    root = Path(machines_root)
    mdir = root / NAME
    if mdir.exists():
        shutil.rmtree(mdir)
    (mdir / "inputs" / "sxrInfo").mkdir(parents=True)

    _dump(mdir / f"{NAME}_settings.yaml", settings(spec))
    rz = wall_polygon(spec)
    with open(mdir / "inputs" / "MOCK_wall.txt", "w") as fh:
        fh.write("".join(f"{R:.6f} {z:.6f}\n" for R, z in rz))

    cfgs = {c.name: camera_config(c, spec) for c in spec.cameras}
    for name, cfg in cfgs.items():
        _dump(mdir / "inputs" / "sxrInfo" / f"{name}_config.yaml", cfg)
    etendues = _analytic_etendues(root, list(cfgs))
    for name, cfg in cfgs.items():
        cfg["ETENDUE"] = etendues[name]
        _dump(mdir / "inputs" / "sxrInfo" / f"{name}_config.yaml", cfg)
    write_equilibrium(mdir / "inputs" / "equilibria" / EQ_FILE, spec)
    return mdir


def mock_workspace(path: str | Path, cameras: list[CameraSpec] | None = None, **spec_changes):
    """
    A workspace at `path` whose MOCK machine is a variant of the shipped one,
    e.g. mock_workspace(tmp_path, cameras=[CameraSpec("A", 90), CameraSpec("B", 225)]).
    """
    from emis3d.workspace import Workspace

    path = Path(path)
    spec = replace(DEFAULT, **spec_changes)
    if cameras is not None:
        spec = replace(spec, cameras=tuple(cameras))
    build(path / "machines", spec)
    return Workspace.resolve(workspace=path, env={}, user_config=path / "_none.yaml")


